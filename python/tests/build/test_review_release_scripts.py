"""scripts/check-versions.sh and scripts/tag-release.sh, run against a
throwaway repository with a bare "origin".

The incident they prevent: v0.1.0 was pushed pointing at a commit whose
version files still said 0.0.1. check-versions.sh read the working tree, so
it passed with the bump uncommitted, and nothing checked the tag itself.
"""

import os
import shutil
import subprocess
import sys
import tempfile
import textwrap
import unittest

from tests import _support

SH, GIT, NODE = shutil.which("sh"), shutil.which("git"), shutil.which("node")
SCRIPTS = os.path.join(_support.REPO_ROOT, "scripts")

# Stands in for gpg: emits a signature block and the status line git expects.
FAKE_SIGNER = textwrap.dedent("""\
    #!/bin/sh
    cat >/dev/null
    echo "[GNUPG:] SIG_CREATED D 22 8 00 0 FAKEKEY" >&2
    printf -- '-----BEGIN PGP SIGNATURE-----\\n\\nZmFrZSBzaWduYXR1cmU=\\n-----END PGP SIGNATURE-----\\n'
    """)


def version_files(py, js, crlf=False, rust=None, lock=None):
    """The version files at these versions. The native engine's (rust/Cargo.toml's
    [workspace.package] and its crates' Cargo.lock entries) follow python's unless
    given; rust=False leaves rust/ out, as in the releases before it."""
    nl = "\r\n" if crlf else "\n"
    files = {
        "python/src/lazaret/__init__.py": f'"""Lazaret."""{nl}__version__ = "{py}"{nl}',
        "js/package.json": f'{{{nl}  "name": "lazaret",{nl}  "version": "{js}"{nl}}}{nl}',
    }
    if rust is not False:
        rust = py if rust is None else rust
        lock = rust if lock is None else lock
        files["rust/Cargo.toml"] = (
            f'[workspace]{nl}resolver = "2"{nl}members = ["crates/lazaret-engine", "crates/lazaret-ffi"]{nl}{nl}'
            f'[workspace.package]{nl}version = "{rust}"{nl}edition = "2021"{nl}rust-version = "1.75"{nl}{nl}'
            f'[profile.release]{nl}lto = true{nl}')
        files["rust/Cargo.lock"] = (
            f'# This file is automatically @generated by Cargo.{nl}version = 3{nl}{nl}'
            f'[[package]]{nl}name = "lazaret-engine"{nl}version = "{lock}"{nl}{nl}'
            f'[[package]]{nl}name = "lazaret-ffi"{nl}version = "{lock}"{nl}'
            f'dependencies = [{nl} "lazaret-engine",{nl}]{nl}')
    return files


@unittest.skipUnless(SH and GIT and NODE, "needs sh, git and node")
class RepoCase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        tmp = self._tmp.name
        home = os.path.join(tmp, "home")
        os.makedirs(home)
        self.env = {k: v for k, v in os.environ.items()
                    if not k.startswith(("GIT_", "GITHUB_", "RELEASE_"))}
        self.env.update(HOME=home, USERPROFILE=home, GIT_CONFIG_NOSYSTEM="1",
                        GIT_AUTHOR_NAME="Test", GIT_AUTHOR_EMAIL="test@example.invalid",
                        GIT_COMMITTER_NAME="Test", GIT_COMMITTER_EMAIL="test@example.invalid")
        self.origin = os.path.join(tmp, "origin.git")
        self.repo = os.path.join(tmp, "work")
        subprocess.run([GIT, "init", "-q", "--bare", self.origin], check=True, env=self.env)
        os.makedirs(os.path.join(self.repo, "scripts"))
        for name in ("check-versions.sh", "tag-release.sh"):
            shutil.copy2(os.path.join(SCRIPTS, name), os.path.join(self.repo, "scripts", name))
        self.git("init", "-q")
        self.git("symbolic-ref", "HEAD", "refs/heads/main")
        self.git("config", "core.autocrlf", "false")
        self.git("remote", "add", "origin", self.origin)
        self.commit(version_files("0.0.1", "0.0.1"), "Release 0.0.1")
        self.git("push", "-q", "origin", "main")

    def git(self, *args, check=True):
        p = subprocess.run([GIT, *args], cwd=self.repo, env=self.env, capture_output=True,
                           encoding="utf-8", errors="replace", timeout=30)
        if check and p.returncode:
            raise AssertionError(f"git {' '.join(args)}: {p.stderr}")
        return p.stdout.strip()

    def write(self, files):
        for rel, text in files.items():
            path = os.path.join(self.repo, *rel.split("/"))
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(text)

    def commit(self, files, msg):
        self.write(files)
        self.git("add", "-A")
        self.git("commit", "-q", "-m", msg)

    def run_script(self, name, *args, env=None):
        return subprocess.run([SH, os.path.join("scripts", name), *args], cwd=self.repo,
                              env=dict(self.env, **(env or {})), capture_output=True,
                              encoding="utf-8", errors="replace", timeout=40)


class CheckVersionsTests(RepoCase):
    def check(self, *args, env=None):
        return self.run_script("check-versions.sh", *args, env=env)

    def test_clean_tree(self):
        p = self.check()
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertIn("python: 0.0.1  npm: 0.0.1  rust: 0.0.1  (working tree)", p.stdout)

    def test_uncommitted_bump_fails_but_head_reads_the_commit(self):
        self.write(version_files("0.1.0", "0.1.0"))
        p = self.check()
        self.assertEqual(p.returncode, 1)
        self.assertIn("uncommitted changes to the version files", p.stderr)
        p = self.check("HEAD")
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertIn("python: 0.0.1  npm: 0.0.1", p.stdout)   # what a tag would get
        p = self.check("HEAD", "v0.1.0")
        self.assertEqual(p.returncode, 1)
        self.assertIn("tag v0.1.0 does not match the committed version v0.0.1", p.stderr)

    def test_a_tag_is_checked_against_its_own_commit(self):
        old = self.git("rev-parse", "HEAD")
        self.git("tag", "v0.0.1")
        self.commit(version_files("0.1.0", "0.1.0"), "Bump version to 0.1.0")
        self.git("tag", "v0.1.0", old)                  # the incident: tag on the old commit
        p = self.check("v0.0.1")
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertIn("tag: v0.0.1 matches", p.stdout)
        p = self.check("v0.1.0")
        self.assertEqual(p.returncode, 1)
        self.assertIn("tag v0.1.0 does not match the committed version v0.0.1", p.stderr)
        self.assertIn("Recovering from a bad tag", p.stderr)
        self.assertEqual(self.check().returncode, 0)    # the tree itself is consistent

    def test_ci_tag_push(self):
        p = self.check(env={"GITHUB_REF_TYPE": "tag", "GITHUB_REF_NAME": "v0.0.1"})
        self.assertEqual(p.returncode, 0, p.stderr)
        p = self.check(env={"GITHUB_REF_TYPE": "tag", "GITHUB_REF_NAME": "v0.1.0"})
        self.assertEqual(p.returncode, 1)
        p = self.check(env={"GITHUB_REF_TYPE": "branch", "GITHUB_REF_NAME": "main"})
        self.assertEqual(p.returncode, 0, p.stderr)

    def test_crlf_files(self):
        self.commit(version_files("0.0.2", "0.0.2", crlf=True), "CRLF")
        for args in ((), ("HEAD",), ("HEAD", "v0.0.2")):
            p = self.check(*args)
            self.assertEqual(p.returncode, 0, p.stderr)
            self.assertIn("python: 0.0.2  npm: 0.0.2  rust: 0.0.2  (", p.stdout)

    def test_the_native_engine_is_released_in_lockstep(self):
        # the engine ships in the platform wheels and names its version in
        # `lazaret --version`: Cargo.toml's workspace version, and Cargo.lock's
        # entries for the two crates, which `cargo build --locked` insists on
        self.commit(version_files("0.0.2", "0.0.2", rust="0.0.1"), "Half a bump: Rust left behind")
        p = self.check()
        self.assertEqual(p.returncode, 1)
        self.assertIn("version mismatch: python 0.0.2, npm 0.0.2, rust 0.0.1", p.stderr)
        self.commit(version_files("0.0.2", "0.0.2", lock="0.0.1"), "Cargo.lock left behind")
        p = self.check("HEAD", "v0.0.2")
        self.assertEqual(p.returncode, 1)
        self.assertIn("rust/Cargo.lock has lazaret-engine 0.0.1, not 0.0.2", p.stderr)
        self.assertIn("cargo update --workspace --offline", p.stderr)
        self.commit(version_files("0.0.2", "0.0.2"), "The whole bump")
        self.assertEqual(self.check("HEAD", "v0.0.2").returncode, 0)
        self.write({"rust/Cargo.toml": version_files("0.0.3", "0.0.3")["rust/Cargo.toml"]})
        p = self.check()
        self.assertEqual(p.returncode, 1)
        self.assertIn("uncommitted changes to the version files", p.stderr)

    def test_every_lazaret_crate_of_the_lock_file_is_bumped(self):
        # lazaret-net and lazaret-verify (0.1.9, NET-1) are workspace crates too, so `cargo build --locked`
        # fails on a lock file that left one behind; pratique keeps the version of its own repository
        files = version_files("0.0.2", "0.0.2")
        lock = files["rust/Cargo.lock"]
        files["rust/Cargo.lock"] = (lock + '\n[[package]]\nname = "lazaret-net"\nversion = "0.0.1"\n'
                                   '\n[[package]]\nname = "pratique"\nversion = "0.1.0"\n')
        self.commit(files, "lazaret-net left behind")
        p = self.check("HEAD", "v0.0.2")
        self.assertEqual(p.returncode, 1)
        self.assertIn("rust/Cargo.lock has lazaret-net 0.0.1, not 0.0.2", p.stderr)
        files["rust/Cargo.lock"] = files["rust/Cargo.lock"].replace('"lazaret-net"\nversion = "0.0.1"',
                                                                '"lazaret-net"\nversion = "0.0.2"')
        self.commit(files, "The whole bump")
        p = self.check("HEAD", "v0.0.2")
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertIn("tag: v0.0.2 matches", p.stdout)

    def test_a_release_from_before_the_native_engine(self):
        old = self.git("rev-parse", "HEAD")
        self.git("rm", "-q", "-r", "rust")
        self.git("commit", "-q", "-m", "As 0.0.1 was: no rust/")
        self.git("tag", "v0.0.1")
        p = self.check("v0.0.1")
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertIn("python: 0.0.1  npm: 0.0.1  rust: -  (", p.stdout)
        self.git("checkout", "-q", old, "--", "rust/Cargo.toml")      # a Cargo.toml without its lock file
        self.git("commit", "-q", "-m", "No lock file")
        p = self.check("HEAD")
        self.assertEqual(p.returncode, 1)
        self.assertIn("no rust/Cargo.lock", p.stderr)

    def test_mismatch_and_unknown_ref(self):
        self.commit(version_files("0.0.2", "0.0.1"), "Half a bump")
        p = self.check()
        self.assertEqual(p.returncode, 1)
        self.assertIn("version mismatch: python 0.0.2, npm 0.0.1", p.stderr)
        p = self.check("no-such-ref")
        self.assertEqual(p.returncode, 1)
        self.assertIn("unknown git ref", p.stderr)


class TagReleaseTests(RepoCase):
    def tag(self, *args):
        return self.run_script("tag-release.sh", *args)

    def use_signer(self, program):
        """Opt in to signing the way RELEASING.md describes (tag.gpgSign)."""
        self.git("config", "gpg.program", program)
        self.git("config", "user.signingkey", "FAKEKEY")
        self.git("config", "tag.gpgSign", "true")

    def assertNoTags(self):
        self.assertEqual(self.git("tag", "-l"), "")
        self.assertEqual(self.git("ls-remote", "--tags", "origin"), "")

    def test_refuses_uncommitted_changes(self):
        self.write({"js/package.json": version_files("0.0.1", "0.0.2")["js/package.json"]})
        p = self.tag()
        self.assertEqual(p.returncode, 1)
        self.assertIn("uncommitted changes", p.stderr)
        self.assertNoTags()

    def test_refuses_a_commit_that_is_not_on_main(self):
        self.commit(version_files("0.0.2", "0.0.2"), "Local only")
        p = self.tag()
        self.assertEqual(p.returncode, 1)
        self.assertIn("is not on refs/remotes/origin/main", p.stderr)
        self.git("switch", "-q", "-c", "feature", "main~0")
        p = self.tag()
        self.assertEqual(p.returncode, 1)
        self.assertNoTags()

    def test_refuses_a_main_that_was_not_pulled(self):
        # v0.1.0 was once tagged on the commit before the merged PR, because
        # the local main was behind origin/main; that commit is "on main" too
        self.commit(version_files("0.0.1", "0.0.1") | {"notes.txt": "merged work\n"}, "Merged PR")
        self.git("push", "-q", "origin", "main")
        self.git("reset", "-q", "--hard", "HEAD~1")        # a clone that never pulled
        p = self.tag()
        self.assertEqual(p.returncode, 1)
        self.assertIn("1 commit(s) behind refs/remotes/origin/main", p.stderr)
        self.assertIn("git pull", p.stderr)
        self.assertNoTags()
        p = self.run_script("tag-release.sh", env={"RELEASE_NOT_LATEST": "1"})   # on purpose
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertEqual(self.git("rev-parse", "v0.0.1^{commit}"), self.git("rev-parse", "HEAD"))

    def test_refuses_a_tag_that_does_not_match_the_committed_version(self):
        p = self.tag("v0.1.0")
        self.assertEqual(p.returncode, 1)
        self.assertIn("does not match the committed version v0.0.1", p.stderr)
        p = self.tag("0.0.1")
        self.assertEqual(p.returncode, 1)
        self.assertIn("vX.Y.Z", p.stderr)
        self.assertNoTags()

    def test_creates_an_annotated_tag_without_a_signing_key(self):
        # Release tags need no signature (the tag ruleset, environment
        # approvals, trusted publishing and npm's 2FA stage approval protect a
        # release); they must be annotated, which the release workflow checks.
        self.git("config", "tag.gpgSign", "false")
        p = self.tag()
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertEqual(self.git("cat-file", "-t", "v0.0.1"), "tag")
        self.assertIn("Lazaret v0.0.1", self.git("cat-file", "tag", "v0.0.1"))
        self.assertNotIn("SIGNATURE-----", self.git("cat-file", "tag", "v0.0.1"))
        self.assertEqual(self.git("rev-parse", "v0.0.1^{commit}"), self.git("rev-parse", "HEAD"))
        self.assertIn("git push origin refs/tags/v0.0.1", p.stdout)
        self.assertNotIn("--tags\n", p.stdout)
        self.assertEqual(self.git("ls-remote", "--tags", "origin"), "")   # it never pushes
        # a second run refuses: the tag exists locally
        p = self.tag()
        self.assertEqual(p.returncode, 1)
        self.assertIn("already exists locally", p.stderr)

    def test_a_failing_opt_in_signer_leaves_no_tag(self):
        self.use_signer("false")               # tag.gpgSign on, signer always fails
        p = self.tag()
        self.assertEqual(p.returncode, 1)
        self.assertIn("could not create the tag", p.stderr)
        self.assertIn("tag.gpgSign", p.stderr)
        self.assertNoTags()

    @unittest.skipIf(sys.platform == "win32", "the fake signer is a shell script")
    def test_signs_the_tag_when_tag_gpgsign_is_on(self):
        signer = os.path.join(self._tmp.name, "fake-gpg")
        with open(signer, "w", newline="\n", encoding="utf-8") as f:
            f.write(FAKE_SIGNER)
        os.chmod(signer, 0o755)
        self.use_signer(signer)
        p = self.tag()
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertEqual(self.git("cat-file", "-t", "v0.0.1"), "tag")
        self.assertIn("-----BEGIN PGP SIGNATURE-----", self.git("cat-file", "tag", "v0.0.1"))

    def test_refuses_a_tag_that_is_already_on_the_remote(self):
        self.git("tag", "v0.0.1")
        self.git("push", "-q", "origin", "refs/tags/v0.0.1")
        self.git("tag", "-d", "v0.0.1")
        p = self.tag()
        self.assertEqual(p.returncode, 1)
        self.assertIn("already exists on origin", p.stderr)
        self.assertIn("Recovering from a bad tag", p.stderr)


if __name__ == "__main__":
    unittest.main()
