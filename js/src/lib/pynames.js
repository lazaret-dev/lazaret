let names = null;
/** The character `name` (a Unicode character name or alias, any case) stands for. */
export function pyCharByName(name) {
  if (!names) {
    names = new Map();
    for (const entry of TABLE.split(";")) {
      const [hex, list] = entry.split(":");
      const ch = String.fromCodePoint(parseInt(hex, 16));
      for (const nm of list.split("|")) names.set(nm, ch);
    }
  }
  return names.get(name.toUpperCase()) ?? "\ufffd";
}
