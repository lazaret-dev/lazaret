#!/usr/bin/env python3
"""Refresh the rule pack's list of Gradle's wrapper checksums (FP-GRADLE-WRAPPER).

    python3 scripts/update_gradle_wrapper_checksums.py              # from services.gradle.org, with network
    python3 scripts/update_gradle_wrapper_checksums.py --from-json wrapper-checksums.json --source "…"
    python3 scripts/update_gradle_wrapper_checksums.py --check      # offline: the pack's list is well formed

The engine judges a `gradle/wrapper/gradle-wrapper.jar` by its SHA-256 against GRADLE_WRAPPER_CHECKSUMS
(rust/crates/lazaret-engine/rules/lazaret-rules.json: version -> checksum, every release Gradle publishes a wrapper
checksum for), as Gradle's own wrapper-validation action does. This script rebuilds that list from Gradle's
services: https://services.gradle.org/versions/all names every version and, for each, its `wrapperChecksumUrl`
(…/gradle-X-wrapper.jar.sha256). It uses the standard library alone, and verifies what it downloads:

- HTTPS with the system's certificate checks, from services.gradle.org, following a redirect only over HTTPS to
  Gradle's download hosts or GitHub's (where services.gradle.org serves its distributions from); any other refused;
- the versions list is a JSON array of objects, each version Gradle's form (`8.5`, `8.5.1`, `8.6-rc-1`,
  `9.0.0-milestone-2`), snapshots and nightlies left out, as the action leaves them out by default;
- each checksum is exactly 64 hexadecimal digits;
- for each version new to the list, the wrapper jar itself is downloaded from the checksum's own URL (without
  `.sha256`) and hashed: its SHA-256 must be the published checksum, and it must be a zip (`PK\\x03\\x04`);
- a version already in the list whose published checksum differs is refused (Gradle never changes a release's
  wrapper); so is a list that would lose a version (`--prune` allows it).

It also writes GRADLE_WRAPPER_NO_CHECKSUM, the versions versions/all lists with no `wrapperChecksumUrl` (3.3 to
4.0.2 and their candidates, whose wrapper jars were not reproducible: a jar whose manifest names one can't be
verified, any other jar matching no checksum is a changed one), and GRADLE_WRAPPER_CHECKSUMS_DATE, the list's date (a
nightly older than it is no newer release).

`--from-json` reads a list in the shape gradle/actions ships (`sources/src/wrapper-validation/wrapper-checksums.json`:
[{"version", "checksum"}], generated by its own update from the same services) instead of fetching, with the same
checks but the jar download; `--source` says where it came from and `--date` its date (the pack's versions with no
checksum are kept: gradle/actions' list holds only those with one). The pack is written back in its canonical form
(scripts/make_rust_tables.py's): GRADLE_WRAPPER_CHECKSUMS, and GRADLE_WRAPPER_CHECKSUMS_SOURCE saying where the list
came from and when.
"""
import argparse
import datetime
import hashlib
import json
import os
import re
import sys
import urllib.parse
import urllib.request

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACK = os.path.join(REPO, "rust", "crates", "lazaret-engine", "rules", "lazaret-rules.json")
VERSIONS_URL = "https://services.gradle.org/versions/all"
HOST = "services.gradle.org"
#: where a download from services.gradle.org may be redirected (Gradle's download hosts; its distributions' GitHub
#: releases): what is downloaded is checked by its checksum either way
REDIRECT_HOSTS = ("services.gradle.org", "downloads.gradle.org", "downloads.gradle-dn.com", "github.com",
                  "objects.githubusercontent.com", "release-assets.githubusercontent.com")
KEY, SOURCE_KEY = "GRADLE_WRAPPER_CHECKSUMS", "GRADLE_WRAPPER_CHECKSUMS_SOURCE"
NO_CHECKSUM_KEY, DATE_KEY = "GRADLE_WRAPPER_NO_CHECKSUM", "GRADLE_WRAPPER_CHECKSUMS_DATE"
DATE_RE = re.compile(r"[0-9]{4}-[0-9]{2}-[0-9]{2}\Z")
VERSION_RE = re.compile(r"[0-9]+(?:\.[0-9]+){1,2}(?:-(?:milestone|rc|preview)-[0-9]+)?\Z")
CHECKSUM_RE = re.compile(r"[0-9a-f]{64}\Z")
MAX_LIST = 64 * 1024 * 1024
MAX_JAR = 4 * 1024 * 1024


class Refused(Exception):
    """What was downloaded is not what it must be."""


class _SameHost(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        parts = urllib.parse.urlsplit(newurl)
        if parts.scheme != "https" or parts.hostname not in REDIRECT_HOSTS:
            raise Refused(f"{req.full_url} redirects to {newurl}, off Gradle's download hosts")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _opener():
    return urllib.request.build_opener(_SameHost())


def fetch(url, limit, opener=None):
    """The bytes at `url` (https://services.gradle.org only), at most `limit`."""
    parts = urllib.parse.urlsplit(url)
    if parts.scheme != "https" or parts.hostname != HOST:
        raise Refused(f"{url} is not on https://{HOST}")
    req = urllib.request.Request(url, headers={"User-Agent": "lazaret-update-gradle-wrapper-checksums"})
    with (opener or _opener()).open(req, timeout=60) as resp:
        data = resp.read(limit + 1)
    if len(data) > limit:
        raise Refused(f"{url} is larger than {limit:,} bytes")
    return data


def published(opener=None):
    """({version: checksum URL} of every release Gradle publishes a wrapper checksum for, [the releases it publishes
    none for]) (no snapshot, no nightly)."""
    data = json.loads(fetch(VERSIONS_URL, MAX_LIST, opener).decode("utf-8"))
    if not isinstance(data, list):
        raise Refused(f"{VERSIONS_URL} is not a JSON array")
    out, none = {}, []
    for entry in data:
        if not isinstance(entry, dict) or not isinstance(entry.get("version"), str):
            raise Refused(f"{VERSIONS_URL} holds an entry that is not a version's: {str(entry)[:80]}")
        if entry.get("snapshot") or entry.get("nightly") or entry.get("releaseNightly"):
            continue
        if not VERSION_RE.match(entry["version"]):
            raise Refused(f"a version that is not Gradle's form: {entry['version']!r}")
        url = entry.get("wrapperChecksumUrl")
        if url:
            out[entry["version"]] = url
        else:
            none.append(entry["version"])
    return out, sorted(set(none))


def checksum_at(url, opener=None):
    text = fetch(url, 1024, opener).decode("ascii", "replace").strip()
    if not CHECKSUM_RE.match(text):
        raise Refused(f"{url} is not a SHA-256: {text[:80]!r}")
    return text


def verify_jar(url, checksum, opener=None):
    """The wrapper jar at the checksum's URL (without .sha256) hashes to `checksum`, and is a zip."""
    jar_url = url[:-len(".sha256")] if url.endswith(".sha256") else None
    if jar_url is None:
        raise Refused(f"{url} does not name a .sha256 beside its jar")
    jar = fetch(jar_url, MAX_JAR, opener)
    if not jar.startswith(b"PK\x03\x04"):
        raise Refused(f"{jar_url} is not a zip")
    got = hashlib.sha256(jar).hexdigest()
    if got != checksum:
        raise Refused(f"{jar_url} hashes to {got}, not the published {checksum}")


def merge(old, new, prune=False):
    """The list with `new` added: a version whose checksum changed, or (without prune) one dropped, refused."""
    for v, c in new.items():
        if v in old and old[v] != c:
            raise Refused(f"Gradle {v}'s wrapper checksum is {c} now, {old[v]} in the list: refused")
    gone = sorted(set(old) - set(new))
    if gone and not prune:
        raise Refused(f"{len(gone)} versions of the list are no longer published ({', '.join(gone[:5])}…): "
                      "--prune to drop them")
    merged = dict(new) if prune else {**old, **new}
    return dict(sorted(merged.items()))


def read_pack(path=PACK):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def current(pack):
    entry = pack["values"].get(KEY, {"map": {}})
    return {v: c["value"] for v, c in entry.get("map", {}).items()}


def no_checksum(pack):
    return sorted(pack["values"].get(NO_CHECKSUM_KEY, {"set": []}).get("set", []))


def write_pack(pack, checksums, source, date, none, path=PACK):
    pack["values"][KEY] = {"map": {v: {"value": c} for v, c in sorted(checksums.items())}}
    pack["values"][SOURCE_KEY] = {"value": source}
    pack["values"][DATE_KEY] = {"value": date}
    pack["values"][NO_CHECKSUM_KEY] = {"set": sorted(none)}
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(pack, indent=1, sort_keys=True, ensure_ascii=True) + "\n")


def check(checksums, none=(), date="2026-10-20"):
    """The list's problems (and its versions with no checksum's, and its date's)."""
    problems = [f"{v!r} is not a Gradle version" for v in checksums if not VERSION_RE.match(v)]
    problems += [f"{v}'s checksum {c!r} is not a SHA-256" for v, c in checksums.items() if not CHECKSUM_RE.match(c)]
    if len(checksums) < 100:
        problems.append(f"the list has {len(checksums)} versions: too few to be Gradle's")
    problems += [f"{v!r}, with no checksum, is not a Gradle version" for v in none if not VERSION_RE.match(v)]
    problems += [f"{v} has a checksum and is listed as having none" for v in none if v in checksums]
    if not DATE_RE.match(date or ""):
        problems.append(f"the list's date {date!r} is not YYYY-MM-DD")
    return problems


def from_json(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, list):
        raise Refused(f"{path} is not a JSON array")
    out = {}
    for entry in data:
        v, c = (entry.get("version"), entry.get("checksum")) if isinstance(entry, dict) else (None, None)
        if not isinstance(v, str) or not VERSION_RE.match(v) or not isinstance(c, str) or not CHECKSUM_RE.match(c):
            raise Refused(f"{path} holds an entry that is not a version and a checksum: {str(entry)[:80]}")
        if v in out and out[v] != c:
            raise Refused(f"{path} gives {v} two checksums")
        out[v] = c
    return out


def _configure_stdio():
    """Redirected output is UTF-8 unless PYTHONIOENCODING says otherwise, and
    never raises on a character the stream can't encode (STRUCTURE.md,
    "Cross-platform rules")."""
    explicit = bool(os.environ.get("PYTHONIOENCODING"))
    for stream in (sys.stdout, sys.stderr):
        try:
            encoding = (getattr(stream, "encoding", None) or "").lower().replace("_", "-")
            if not explicit and not stream.isatty() and encoding not in ("utf-8", "utf8"):
                stream.reconfigure(encoding="utf-8", errors="replace")
            else:
                stream.reconfigure(errors="replace")
        except (AttributeError, OSError, ValueError):
            pass


def main(argv, opener=None, today=None):
    _configure_stdio()
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--pack", default=PACK)
    ap.add_argument("--check", action="store_true", help="offline: the pack's list is well formed")
    ap.add_argument("--from-json", metavar="FILE", help="read gradle/actions' wrapper-checksums.json instead")
    ap.add_argument("--source", help="where --from-json's list came from (recorded in the pack)")
    ap.add_argument("--date", help="--from-json's list's date, YYYY-MM-DD (default: today)")
    ap.add_argument("--prune", action="store_true", help="drop versions Gradle no longer publishes")
    a = ap.parse_args(argv)
    pack = read_pack(a.pack)
    old = current(pack)
    if a.check:
        problems = check(old, no_checksum(pack), pack["values"].get(DATE_KEY, {}).get("value"))
        for p in problems:
            print(p, file=sys.stderr)
        if not problems:
            print(f"{len(old)} versions, {len(set(old.values()))} checksums; {pack['values'][SOURCE_KEY]['value']}")
        return 1 if problems else 0
    today = today or datetime.date.today().isoformat()
    try:
        if a.from_json:
            new = from_json(a.from_json)
            source = a.source or f"{a.from_json}, read {today}"
            date, none = a.date or today, no_checksum(pack)
        else:
            urls, none = published(opener)
            date = today
            new = {}
            for v, url in sorted(urls.items()):
                c = checksum_at(url, opener)
                if v not in old:
                    verify_jar(url, c, opener)
                new[v] = c
            source = f"{VERSIONS_URL} (each version's wrapperChecksumUrl; new versions' jars hashed), {today}"
        merged = merge(old, new, a.prune)
    except (Refused, OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    problems = check(merged, none, date)
    if problems:
        for p in problems:
            print(p, file=sys.stderr)
        return 1
    added = sorted(set(merged) - set(old))
    write_pack(pack, merged, source, date, none, a.pack)
    print(f"{len(merged)} versions ({len(added)} new{': ' + ', '.join(added[:10]) if added else ''})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
